#!/usr/bin/env bash
# EM-002 — Verify the toolchain and Apple Development signing identity for EchoMinutes.
# Usage: scripts/check-signing.sh [--write-local]
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WRITE_LOCAL=0; [[ "${1:-}" == "--write-local" ]] && WRITE_LOCAL=1
ok()   { printf "  \033[32m✔\033[0m %s\n" "$*"; }
warn() { printf "  \033[33m!\033[0m %s\n" "$*"; }
fail() { printf "  \033[31m✘\033[0m %s\n" "$*"; FAILED=1; }
FAILED=0

echo "== System =="
OSV="$(sw_vers -productVersion)"; ARCH="$(uname -m)"
echo "  macOS $OSV ($ARCH)"
IFS=. read -r MAJ MIN _ <<<"$OSV"; MIN=${MIN:-0}
if (( MAJ > 14 || (MAJ == 14 && MIN >= 4) )); then ok "macOS ≥ 14.4 (process taps available)"; else fail "macOS 14.4+ required (found $OSV)"; fi
[[ "$ARCH" == "arm64" ]] && ok "Apple Silicon" || warn "Intel Mac — local Whisper will be slow"

echo "== Xcode =="
if XV="$(xcodebuild -version 2>/dev/null)"; then
  ok "$(echo "$XV" | tr '\n' ' ')"
  ok "Developer dir: $(xcode-select -p)"
else
  fail "xcodebuild not found. Install Xcode, then: sudo xcode-select -s /Applications/Xcode.app"
fi
command -v swiftc >/dev/null && ok "$(swiftc --version 2>&1 | head -1)" || fail "swiftc not found"

echo "== Code-signing identities =="
IDS="$(security find-identity -v -p codesigning 2>/dev/null)"
echo "$IDS" | sed 's/^/  /'
DEV_LINE="$(echo "$IDS" | grep '"Apple Development:' | head -1)"
if [[ -z "$DEV_LINE" ]]; then
  ALL="$(security find-identity -p codesigning 2>/dev/null | grep '"Apple Development:')"
  if [[ -n "$ALL" ]]; then
    echo "  Found but NOT valid:"; echo "$ALL" | sed 's/^/    /'
    if echo "$ALL" | grep -q 'CSSMERR_TP_NOT_TRUSTED'; then
      fail "Certificate not trusted — install Apple's intermediate certificate:"
      echo "      curl -fsSLO https://www.apple.com/certificateauthority/AppleWWDRCAG3.cer && open AppleWWDRCAG3.cer"
      echo "      (add it to the 'login' keychain, then re-run this script)"
    else
      fail "Certificate present but unusable (see reason above). If no private key on this Mac, delete it in Xcode ▸ Manage Certificates and create a new one."
    fi
  else
  fail "No 'Apple Development' identity. Xcode ▸ Settings ▸ Accounts ▸ (your Apple ID) ▸ Manage Certificates ▸ + ▸ Apple Development"
  fi
else
  SHA1="$(echo "$DEV_LINE" | awk '{print $2}')"
  NAME="$(echo "$DEV_LINE" | sed -E 's/.*"(.*)".*/\1/')"
  SUBJECT="$(security find-certificate -c "$NAME" -p 2>/dev/null | openssl x509 -noout -subject 2>/dev/null)"
  TEAM_ID="$(echo "$SUBJECT" | sed -nE 's/.*OU *= *([A-Z0-9]{10}).*/\1/p')"
  EXPIRY="$(security find-certificate -c "$NAME" -p 2>/dev/null | openssl x509 -noout -enddate 2>/dev/null | cut -d= -f2)"
  ok "Identity: $NAME"
  ok "SHA-1:    $SHA1"
  [[ -n "$TEAM_ID" ]] && ok "Team ID:  $TEAM_ID" || fail "Could not read Team ID from certificate subject: $SUBJECT"
  [[ -n "$EXPIRY" ]] && ok "Expires:  $EXPIRY (renew before this or TCC permissions may reset)"
  N="$(echo "$IDS" | grep -c '"Apple Development:')"
  (( N > 1 )) && warn "$N Apple Development identities found — Xcode Automatic signing picks by team; keep one per team to avoid surprises"
  echo "$IDS" | grep -q '"Developer ID Application:' && ok "Developer ID Application identity present (for notarized release builds)" \
    || warn "No Developer ID Application identity — fine for personal use; needed only to notarize/distribute"

  if (( WRITE_LOCAL )) && [[ -n "$TEAM_ID" ]]; then
    cat > "$ROOT/Config/Signing.local.xcconfig" <<XC
// Generated by scripts/check-signing.sh on $(date +%F). Git-ignored.
DEVELOPMENT_TEAM = $TEAM_ID
EM_SIGNING_IDENTITY_SHA1 = $SHA1
XC
    ok "Wrote Config/Signing.local.xcconfig"
  fi
fi

echo
(( FAILED )) && { echo "Result: ✘ fix the items above"; exit 1; } || echo "Result: ✔ signing environment ready"
